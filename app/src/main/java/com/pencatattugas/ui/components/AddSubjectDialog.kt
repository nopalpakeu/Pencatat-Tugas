@OptIn(ExperimentalLayoutApi::class)
@Composable
fun AddSubjectDialog(
    onDismiss: () -> Unit,
    onSaveSubject: (name: String, teacherName: String, colorHex: Long) -> Unit
) {
    var name by remember { mutableStateOf("") }
    var teacherName by remember { mutableStateOf("") }

    val presetColors = listOf(
        0xFF1E88E5, // Blue
        0xFF43A047, // Green
        0xFF8E24AA, // Purple
        0xFFFB8C00, // Orange
        0xFFE53935, // Red
        0xFF00ACC1, // Cyan
        0xFFD81B60, // Pink
        0xFF5E35B1, // Deep Purple
        0xFF00897B, // Teal
        0xFF6D4C41  // Brown
    )
    var selectedColor by remember { mutableLongStateOf(presetColors.first()) }

    AlertDialog(
        onDismissRequest = onDismiss,
        title = {
            Text(
                text = "Tambah Mata Pelajaran",
                style = MaterialTheme.typography.titleLarge.copy(fontWeight = FontWeight.Bold)
            )
        },
        text = {
            Column(modifier = Modifier.fillMaxWidth()) {
                OutlinedTextField(
                    value = name,
                    onValueChange = { name = it },
                    label = { Text("Nama Mata Pelajaran *") },
                    placeholder = { Text("Contoh: Sosiologi") },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth()
                )

                Spacer(modifier = Modifier.height(10.dp))

                OutlinedTextField(
                    value = teacherName,
                    onValueChange = { teacherName = it },
                    label = { Text("Nama Guru / Pengampu (Opsional)") },
                    placeholder = { Text("Contoh: Bu Siti") },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth()
                )

                Spacer(modifier = Modifier.height(16.dp))

                Text(
                    text = "Pilih Warna Label",
                    style = MaterialTheme.typography.labelMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
                Spacer(modifier = Modifier.height(8.dp))

                FlowRow(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(10.dp),
                    verticalArrangement = Arrangement.spacedBy(10.dp)
                ) {
                    presetColors.forEach { colorHex ->
                        val isSelected = selectedColor == colorHex
                        Box(
                            modifier = Modifier
                                .size(36.dp)
                                .clip(CircleShape)
                                .background(Color(colorHex))
                                .border(
                                    width = if (isSelected) 3.dp else 1.dp,
                                    color = if (isSelected) MaterialTheme.colorScheme.primary else Color.Transparent,
                                    shape = CircleShape
                                )
                                .clickable { selectedColor = colorHex },
                            contentAlignment = Alignment.Center
                        ) {
                            if (isSelected) {
                                Icon(
                                    imageVector = Icons.Default.Check,
                                    contentDescription = "Terpilih",
                                    tint = Color.White,
                                    modifier = Modifier.size(20.dp)
                                )
                            }
                        }
                    }
                }
            }
        },
        confirmButton = {
            Button(
                onClick = {
                    if (name.isNotBlank()) {
                        onSaveSubject(name, teacherName, selectedColor)
                        onDismiss()
                    }
                },
                enabled = name.isNotBlank()
            ) {
                Text("Simpan")
            }
        },
        dismissButton = {
            TextButton(onClick = onDismiss) {
                Text("Batal")
            }
        }
    )
}
